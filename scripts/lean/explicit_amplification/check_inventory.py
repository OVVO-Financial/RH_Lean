#!/usr/bin/env python3
"""Read-only public-type/import/export audit for the explicit amplification proof.

The parser and binder handling are the existing total-mass audit. Expected
types and hashes are reviewed, committed inputs; this checker never rewrites
them and never executes Lean. The separate CI step elaborates ExactTypes.lean.
"""

from __future__ import annotations

import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "scripts/lean/total_mass"))
import check_inventory as base

SOURCES = (
    "RHLean/Proof/SquareRootAmplificationPowerBounds.lean",
    "research/oai_434/VF919ExplicitSlotTotalMass.lean",
    "research/oai_434/VF919ExplicitAmplificationBound.lean",
)
BUNDLE = Path("scripts/lean/explicit_amplification")


def render_exact_types(sources: list[base.Source]) -> str:
    original = base.render_exact_types(sources)
    body = original.split("set_option autoImplicit false\n\n", 1)[1]
    return (
        "import «research.oai_434.VF919ExplicitAmplificationBound»\n\n"
        "/-! Exact quantified public types for the explicit amplification proof.\n"
        "The terminal types retain the actual centered Mertens source, historical\n"
        "maximum, every positive loss, fixed constants and natural cutoffs.\n"
        "These are committed expectations, never regenerated by CI. -/\n\n"
        "set_option autoImplicit false\n\n" + body
    )


def actual_inventory(root: Path) -> tuple[dict[str, object], str]:
    sources = [base.read_source(root, path) for path in SOURCES]
    types = render_exact_types(sources)
    result = base.expected_manifest(sources, types)
    names = [d.name for source in sources for d in source.declarations]
    if len(names) != len(set(names)):
        raise ValueError("duplicate public declaration name")
    root_import = "import RHLean.Proof.SquareRootAmplificationPowerBounds"
    if (root / "RHLean.lean").read_text().splitlines().count(root_import) != 1:
        raise ValueError("the generic exact amplification consumer must be exported once")
    result["root_export"] = root_import
    return result, types


def main() -> int:
    root = Path(sys.argv[1]).resolve() if len(sys.argv) == 2 else ROOT
    if len(sys.argv) > 2:
        raise ValueError("usage: check_inventory.py [repository-root]")
    actual, types = actual_inventory(root)
    expected = json.loads((root / BUNDLE / "expected_inventory.json").read_text())
    if actual != expected:
        raise ValueError("public names, types, imports, scopes or exports changed")
    if (root / BUNDLE / "ExactTypes.lean").read_text() != types:
        raise ValueError("ExactTypes.lean differs from committed quantified expectations")
    (root / "explicit-amplification-inventory.json").write_text(
        json.dumps(actual, indent=2) + "\n"
    )
    print(
        f"PASS explicit amplification inventory: {len(SOURCES)} source files, "
        f"{actual['public_theorems']} public theorems, "
        f"{actual['public_definitions']} definitions; exact types and root export pinned"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
