#!/usr/bin/env python3
"""Generate reviewable Lean extensions; never modify the pinned input files.

The generated theorems weaken beta >= 7/8 to beta >= 7/8 - e/2,
charge the resulting e/2 in the floor and large-tail budgets, and use
physical tilt e/2. Every generated theorem must be kernel checked.
Generation itself is NOT proof acceptance. Input Git blob hashes and
mandatory textual replacements fail closed when the source changes.
"""
from __future__ import annotations
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "research/oai_434"
SUFFIX = "_near_endpoint"
DECL = re.compile(r"^(?:private\s+)?(?:theorem|lemma|def)\s+([A-Za-z_][A-Za-z_0-9.]*)", re.M)


def read_checked(path: str, expected: str) -> str:
    raw = (ROOT / path).read_bytes()
    actual = hashlib.sha1(b"blob " + str(len(raw)).encode() + b"\0" + raw).hexdigest()
    if actual != expected:
        raise RuntimeError(f"Pinned input changed: {path}: {actual} != {expected}")
    return raw.decode("utf-8")


def replace_required(text: str, old: str, new: str, count: int | None = None) -> str:
    n = text.count(old)
    if not n or (count is not None and n != count):
        raise RuntimeError(f"Unexpected replacement count {n}: {old!r}; expected {count}")
    return text.replace(old, new)


def rename(text: str, names: set[str]) -> str:
    for name in sorted(names, key=len, reverse=True):
        text = re.sub(r"(?<![A-Za-z_0-9])" + re.escape(name) + r"(?![A-Za-z_0-9])", name + SUFFIX, text)
    return text


def generate(name: str, text: str, imports: list[str], names: set[str]) -> None:
    text = rename(text, names)
    old_imports = re.findall(r"^import [^\n]+", text, re.M)
    text = re.sub(r"^import [^\n]+\n", "", text, flags=re.M)
    all_imports = list(dict.fromkeys(imports + old_imports))
    header = """\n\n/-! Generated by scripts/generate_quantitative_tilt.py.
The original signed source and normalizer are unchanged. The modified
hypotheses and all proof obligations are checked by Lean, not by this script.
-/\n"""
    text = "\n".join(all_imports) + header + text
    path = OUT / f"{name}.lean"
    path.write_text(text, encoding="utf-8")
    print(path.relative_to(ROOT))


def main() -> None:
    small = read_checked("oai-upstream/lean/OAI/NumberTheory/DirichletL/PrimeRows/SmallTail.lean", "671bd671720957900dd8e2760bd1c3d2f03b1356")
    tails = read_checked("research/oai_434/VF919TiltedHighTails.lean", "6ae8ea83aca3d3f8ba8d65d42f2a6a4428e6b84f")
    transport = read_checked("research/oai_434/VF919TiltedHighTransport.lean", "50c46fb1c5629865c3b7a6546ed3d9418fff1391")
    assembly = read_checked("research/oai_434/VF919TiltedHighAssembly.lean", "883141e0af896d4132bfc4ffa076e2d265ece5c9")
    names = set(DECL.findall(small + "\n" + tails + "\n" + transport + "\n" + assembly))
    old_beta = "(hβ : (7/8:ℝ)≤HeckeZeroSupremum.beta)"
    new_beta = "(hβ : (7/8:ℝ)-e/2≤HeckeZeroSupremum.beta)"
    small = replace_required(small, old_beta, new_beta)
    tails = replace_required(tails, old_beta, new_beta)
    transport = replace_required(transport, old_beta, new_beta)
    transport = replace_required(transport,
        "(hlarge : sigma+nu≤saving+3/16)",
        "(hlarge : sigma+nu+e/2≤saving+3/16)")
    transport = replace_required(transport,
        "(hfloorbudget : 2*ζ+26*e+(K+8)*eps+loss+mesh/6+nu+sigma≤7/1200)",
        "(hfloorbudget : 2*ζ+26*e+(K+8)*eps+loss+mesh/6+nu+sigma+e/2≤7/1200)", 1)
    transport = replace_required(transport,
        "nu hnu ζ sigma hζ.le (by linarith) hsigma hfloorbudget",
        "nu hnu ζ (sigma+e/2) hζ.le (by linarith) (by positivity) (by linarith only [hfloorbudget])", 1)
    transport = replace_required(transport,
        "Z^(3/16-sigma-8*tilt)", "Z^(3/16-(sigma+e/2)-8*tilt)", 1)
    assembly = replace_required(assembly,
        "theorem fixed_tilted_high_bound (hβ : (7/8:ℝ)≤HeckeZeroSupremum.beta)\n    (D : HighData (1/1000000:ℝ))",
        "theorem fixed_tilted_high_bound (D : HighData (1/1000000:ℝ))\n    (hβ : (7/8:ℝ)-D.e/2≤HeckeZeroSupremum.beta)", 1)
    assembly = replace_required(assembly, old_beta, new_beta, 1)
    assembly = replace_required(assembly,
        "(hfloorbudget : 2*ζ+26*e+(N+8)*eps+loss+mesh/6+nu+sigma≤7/1200)",
        "(hfloorbudget : 2*ζ+26*e+(N+8)*eps+loss+mesh/6+nu+sigma+e/2≤7/1200)", 1)
    assembly = replace_required(assembly, "D.e/48", "D.e/2")
    assembly = replace_required(assembly, "source_gain_budgets D", "enlarged_source_gain_budgets D", 1)
    assembly = replace_required(assembly, "  have hpayment := fixed_delta_target_payment D\n", "", 1)
    assembly = replace_required(assembly,
        "D.window_budget D.floor_budget (by linarith only [hpayment,hβ]) counts",
        "D.window_budget (by linarith only [heps,he,D.high_saving,D.t_small])\n    (by linarith only [hβ,D.high_saving,D.t_small,he]) counts", 1)
    generate("VF919QuantitativeSmallTail", small,
        ["import OAI.NumberTheory.DirichletL.PrimeRows.SmallTail"], names)
    generate("VF919QuantitativeHighTails", tails,
        ["import «research.oai_434.VF919QuantitativeSmallTail»", "import «research.oai_434.VF919TiltedHighTails»"], names)
    generate("VF919QuantitativeHighTransport", transport,
        ["import «research.oai_434.VF919QuantitativeHighTails»", "import «research.oai_434.VF919TiltedHighTransport»"], names)
    generate("VF919QuantitativeHighAssembly", assembly,
        ["import «research.oai_434.VF919QuantitativeHighTransport»", "import «research.oai_434.VF919QuantitativeTiltBudgets»", "import «research.oai_434.VF919TiltedHighAssembly»"], names)


if __name__ == "__main__":
    main()
